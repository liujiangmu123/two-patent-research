# -*- coding: utf-8 -*-
"""C04 动作期间供油校核（蓄能器+泵）、蓄能器容积选择、阀块流道、控制参数整定 -> 数据/c04_动作供油与控制参数.json"""
from common import *

c02 = load("c02_刚度与热漂移.json"); c03 = load("c03_蓄能器与能耗.json")
R = {}
Qe = pump["理论流量_L_min"] * pump["容积效率"] * 1e3 / 60  # cm3/s
pmin, pmax, p0 = acc["最低工作压力_pmin"], acc["最高工作压力_pmax"], acc["充气压力_p0_20C"]

def usable(V0L, p0_, n=1.4):
    a, b, c = pmin + P_ATM, pmax + P_ATM, p0_ + P_ATM
    return V0L * 1e3 * ((c / a) ** (1 / n) - (c / b) ** (1 / n))

# 1 卡盘夹紧 1.2 s：需油 Ac2*S
V_cl = Ac2 * chuck["行程"] / 1e3
t_cl = 1.2
need_acc = V_cl - Qe * t_cl
rows = []
for V0L in [0.7, 1.0, 1.4, 2.0]:
    rows.append({"V0_L": V0L, "可用_绝热_cm3": usable(V0L, p0), "满足卡盘1.2s夹紧": usable(V0L, p0) >= need_acc})
R["卡盘夹紧供油"] = {"需油_cm3": V_cl, "泵1.2s供油_cm3": Qe * t_cl, "需蓄能器补_cm3": need_acc, "容积表": rows,
                "结论": "基准 1.0 L/p0 4.5 MPa 可用约 111 cm3 > 需补，满足；余量小，夹紧末端压力会降至 pmin 附近"}
# 泵单独完成夹紧所需时间
R["卡盘夹紧供油"]["仅泵供油夹紧时间_s"] = V_cl / Qe

# 2 尾座前进 14 s：A1*70 = 218 cm3，泵供 1218 cm3，泵单独满足
V_adv = A1 * x_rated / 1e3
R["尾座前进供油"] = {"需油_cm3": V_adv, "泵14s供油_cm3": Qe * 14, "满足": Qe * 14 > V_adv}

# 3 蓄能器充液时间
dV = c03["蓄能器"]["可用容积_绝热n1.4_cm3"]
R["蓄能器充液"] = {"pmin→pmax充液时间_s": dV / Qe, "首次0→pmax充液时间_s(近似,等温)":
                 acc["容积_L"] * 1e3 * (1 - (p0 + P_ATM) / (pmax + P_ATM)) / Qe}

# 4 阀块流道（尾座支路流量 ≤1 L/min，按 v≤2 m/s 选孔径）
q_tail = 1.0e6 / 60  # mm3/s
d_min = math.sqrt(4 * q_tail / (math.pi * 2000))
R["锁闭阀块55流道"] = {"尾座最大流量_L_min": 1.0, "流速限_m_s": 2.0, "最小孔径_mm": d_min,
                   "取孔径_mm": 6.0, "6mm孔流速_m_s": q_tail / area(6) / 1000,
                   "阀块内每腔流道容积估算_cm3": (area(6) * 120 + area(6) * 60) / 1e3,
                   "说明": "每腔流道长按 120+60 mm 估算，加座阀腔、传感器腔，控制在基准 15 cm3 以内"}

# 5 阻尼孔 22（方案乙微泄）：Δp≈p1，Q=Cd*A*sqrt(2Δp/ρ)，目标单次脉冲 50 ms 降推力 ≤ 半带宽
sens = c02["双腔预压锁闭_阀块直装"]["泄漏灵敏度_N_per_cm3"]  # 单腔放油对推力约 β·A1/V1 → 用单腔灵敏度
sens1 = c02["单腔锁闭_阀块直装"]["泄漏灵敏度_N_per_cm3"]
dF_target = 150.0  # N，半带宽
V_pulse = dF_target / sens1  # cm3
t_pulse = 0.05
Q_need = V_pulse * 1e3 / t_pulse  # mm3/s
p1 = p1_set(F0); Cd = 0.61
A_or = Q_need / (Cd * math.sqrt(2 * p1 * 1e6 / rho) * 1e3)
R["阻尼孔22"] = {"目标单脉冲推力降_N": dF_target, "脉冲时长_s": t_pulse, "所需放油_cm3": V_pulse,
               "计算孔径_mm": math.sqrt(4 * A_or / math.pi), "建议": "取 Ø0.3 mm 标准阻尼塞（可选 0.2/0.4 调试），脉冲宽度软件可调 20~100 ms"}
d03 = 0.3; Aor = area(d03)
Q03 = Cd * Aor * math.sqrt(2 * p1 * 1e6 / rho) * 1e3  # mm3/s
R["阻尼孔22"]["Ø0.3_50ms推力降_N"] = Q03 * t_pulse / 1e3 * sens1
tab = []
for dd in [0.1, 0.15, 0.2, 0.3]:
    Q = Cd * area(dd) * math.sqrt(2 * p1 * 1e6 / rho) * 1e3
    rate = Q / 1e3 * sens1  # N/s
    tab.append({"孔径_mm": dd, "推力降速率_N_s": rate, "降半带宽所需脉冲_ms": dF_target / rate * 1e3})
R["阻尼孔22"]["孔径表"] = tab
R["阻尼孔22"]["建议"] = "即使 Ø0.1 mm，半带宽也只需约 35 ms，与座阀开关时间 20~50 ms 同量级，单脉冲难以精确控制；方案乙需 Ø0.1 mm 双级串联阻尼（流量约降为 1/√2）并前置 10 µm 保护滤网，按小步多脉冲闭环。方案乙可控性明显差于方案甲，仅作备选"

# 6 控制参数
dF_band = 0.05 * F0
T_leak = c02["泄漏推力衰减"]["双腔预压锁闭_座阀"]["越下限时间_min"] * 60
R["控制参数"] = {
    "F0_N": F0, "δ": 0.05, "F_L_N": 0.95 * F0, "F_H_N": 1.05 * F0, "F_safe_N": 1.25 * F0,
    "p1_set_MPa": p1, "p_pre_MPa": p_pre,
    "R1设定_MPa": p1, "R2设定_MPa": p_pre, "R1机械限位上限_MPa(对应F≤18kN,p2=p_pre)": (18000 + p_pre * A2) / A1,
    "滤波": "推力一阶低通 τ=0.2 s（假设；滤除切削力波动，保留热漂移与泄漏趋势）",
    "越带确认时间_s": 0.5, "回复保持时间_s": 0.3, "回复完成判据": "|F−F0|≤0.02F0 持续 0.1 s 后关阀",
    "回复超时_s": 2.0,
    "泄漏诊断": {"额定回复间隔_s(计算)": T_leak, "报警阈值_s(取计算值1/4,对应内泄漏4倍)": T_leak / 4,
               "说明": "回复间隔受油温漂移与工件伸长影响，需按 T1 扣除热漂移后统计（仅计泄漏导致的下越带）"},
    "蓄能器启泵_MPa": pmin, "蓄能器停泵_MPa": pmax, "V0开启前提": "需要供油的动作或回复",
    "卡盘复压周期_s": 60, "卡盘复压时长_s": 0.5,
    "卡盘压力下限p_min(n)": "p_min = max(0.49, pc·(1+k_n·n²)) 的形式由卡盘离心力曲线给出（待按卡盘样本整定）",
    "PLC扫描_ms": B["控制器27"]["扫描周期_ms"],
}
# 推力测量误差：两传感器 0.25%FS×10 MPa
e_p = 0.0025 * 10
eF = math.sqrt((e_p * A1) ** 2 + (e_p * A2) ** 2)
R["推力测量误差"] = {"单传感器误差_MPa": e_p, "推力误差_N(RSS)": eF, "推力误差_N(最坏)": e_p * (A1 + A2),
                 "占带宽比(半带宽300N)": eF / dF_band,
                 "说明": "静摩擦 150 N（50~300）为另一项系统误差，可用试验台推力传感器 49 标定扣除"}
# 静摩擦对推力传递
R["摩擦影响"] = {"静摩擦_N": tail["静摩擦力_N"], "占F0": tail["静摩擦力_N"] / F0,
               "说明": "锁闭后活塞位移极小（µm 级）处于预滑动区，摩擦表现为附加刚度并使 F 计算值与顶尖实际力存在 ±Ff 偏差"}

dump("c04_动作供油与控制参数.json", R, "c04_动作供油与控制参数.py")
