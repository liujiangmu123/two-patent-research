# -*- coding: utf-8 -*-
"""P4 试验台校核计算：楔块分辨率、行程与自锁，丝杠驱动转矩与反驱，推力量程，加载回路与床身刚度，
温控夹套功率与升温速率，泄漏模拟针阀。输出 校核计算.json 与 校核计算书.md（数值由本脚本生成，文本不手填）。
用法：.venv\\Scripts\\python.exe 03_校核计算\\p4_calc.py"""
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
B = json.load(open(os.path.join(PKG, "00_设计基准", "P4_设计基准.json"), encoding="utf-8"))
B1 = json.load(open(os.path.normpath(os.path.join(PKG, B["P1基准"]["文件"])), encoding="utf-8"))
R = {}

# ------------------------------------------------------------------ 1 楔块位移缩小与分辨率
U = B["微位移加载单元"]
t = U["楔块斜率_tan"]
lead = U["滚珠丝杠"]["导程_mm"]
enc = 2 ** U["伺服电机"]["编码器位数"]
res_theory_um = lead / enc * t * 1000
stroke_slider = U["滚珠丝杠"]["有效行程_mm"] * t
R["1_分辨率与行程"] = {
    "楔块斜率tanθ": t, "位移缩小比": round(1 / t, 1), "丝杠导程_mm": lead, "编码器每转脉冲": enc,
    "滑块理论分辨率_um": round(res_theory_um, 4),
    "滑块分辨率目标_um": U["位移分辨率目标_um"],
    "说明": "理论分辨率远小于目标值；实际分辨率受丝杠预紧、楔面接触变形与摩擦粘滑限制，目标 0.5 µm 以位移传感器 56 实测为准",
    "丝杠有效行程_mm": U["滚珠丝杠"]["有效行程_mm"], "滑块轴向行程_mm": round(stroke_slider, 2),
    "需求_热伸长最大_um": max(w["伸长_um"] for w in B1["工件热伸长"]["典型工件"]),
    "行程裕量倍数": round(stroke_slider * 1000 / max(w["伸长_um"] for w in B1["工件热伸长"]["典型工件"]), 1),
}

# ------------------------------------------------------------------ 2 驱动力、转矩、自锁与反驱
F = U["最大轴向加载力_N"]
eta, eta_r = U["滚珠丝杠"]["机械效率"], U["滚珠丝杠"]["逆效率"]
out = {}
for case, mu in (("滑动接触", U["楔面与挡壁摩擦"]["滑动_μ"]), ("滚针接触", U["楔面与挡壁摩擦"]["滚动_μ"])):
    # 楔块受力：斜面法向力 N2 与挡壁法向力 N1；楔块推进需克服两面摩擦（小角度近似精确式）
    th = math.atan(t)
    Ft_push = F * (math.tan(th) + mu + mu * (1 + math.tan(th) * mu)) / (1 - mu * math.tan(th))
    Ft_back = F * (math.tan(th) - mu - mu) / (1 + mu * math.tan(th))       # 轴向力反推楔块的净横向力（>0 不自锁）
    T_push = Ft_push * lead / 1000 / (2 * math.pi * eta)
    T_back = max(Ft_back, 0) * lead / 1000 * eta_r / (2 * math.pi)
    out[case] = {"μ": mu, "推进楔块所需横向力_N": round(Ft_push), "丝杠驱动转矩_Nm": round(T_push, 2),
                 "楔块反推净横向力_N": round(Ft_back), "楔面自锁": Ft_back <= 0,
                 "电机静止保持转矩_Nm": round(T_back, 2),
                 "额定转矩裕量倍数": round(U["伺服电机"]["额定转矩_Nm"] / T_push, 2)}
R["2_驱动与自锁"] = out
R["2_驱动与自锁"]["结论"] = ("滚针接触时驱动转矩约为伺服额定转矩的 {:.0%}，楔面不自锁，静止时需伺服保持或抱闸；"
                         "滑动接触时自锁、但驱动转矩超过额定值，须降速增扭或减小最大加载力").format(
    out["滚针接触"]["丝杠驱动转矩_Nm"] / U["伺服电机"]["额定转矩_Nm"])

# ------------------------------------------------------------------ 3 推力量程
TF = B1["尾座推力"]
R["3_推力量程"] = {"目标推力可调范围_N": TF["F0_可调范围"], "允许最大油缸力_N": TF["允许最大油缸力"],
                "推力传感器量程_N": B["传感器"]["推力传感器49"]["量程_kN"] * 1000,
                "推力传感器误差_N": B["传感器"]["推力传感器49"]["量程_kN"] * 1000 * B["传感器"]["推力传感器49"]["精度_FS"],
                "额定推力F0_N": TF["F0_额定"],
                "误差占额定推力带宽比例": round(B["传感器"]["推力传感器49"]["量程_kN"] * 1000 * B["传感器"]["推力传感器49"]["精度_FS"] / (0.05 * TF["F0_额定"]), 3),
                "说明": "推力带取 ±5%F0；传感器误差约为带宽的 7%，能分辨越带"}

# ------------------------------------------------------------------ 4 加载回路刚度
S = B["模拟床身43"]["截面"]
A_bed = S["下层宽"] * S["下层高"] + S["上层宽"] * S["上层高"]
L_bed = B["模拟床身43"]["加载座至尾座体受力段长_mm"]
k_bed = B["模拟床身43"]["E_MPa"] * A_bed / L_bed / 1000          # N/µm
k_sens = B["传感器"]["推力传感器49"]["轴向刚度_N_um"]
k_tail = B1["额定工况推导值"]["K_双腔预压锁闭_串联_N_um"]
k_loop = 1 / (1 / k_bed + 1 / k_sens)
R["4_回路刚度"] = {"床身受力截面积_mm2": A_bed, "受力段长_mm": L_bed, "床身拉压刚度_N_um": round(k_bed),
                "推力传感器刚度_N_um": k_sens, "加载链串联刚度_N_um(不含楔面接触)": round(k_loop),
                "被测尾座锁闭刚度_N_um": k_tail, "加载链/被测刚度": round(k_loop / k_tail, 1),
                "说明": "加载链刚度远大于被测尾座刚度时，伺服给定位移基本全部作用于尾座；比值的不确定部分（楔面接触、螺栓结合面）由位移传感器 56 直接测滑块位移消除"}

# ------------------------------------------------------------------ 5 温控夹套
T = B["温控"]
H = T["热容组成"]
C = H["缸筒与端盖_钢_kg"] * H["钢比热_J_kgK"] + H["油液_kg"] * H["油比热_J_kgK"] + H["夹套_铝_kg"] * H["铝比热_J_kgK"]
rate_max = max(T["目标漂移速率_K_min"]) / 60
P_rate = C * rate_max
P_loss = T["对流换热系数_W_m2K"] * T["散热面积_m2"] * 10      # 与室温相差 10 K 时的散热
P_need = P_rate + P_loss
tau = C / (T["对流换热系数_W_m2K"] * T["散热面积_m2"])
step_t_min = C * T["目标阶跃幅值_K"] / (T["循环恒温槽85"]["制冷功率_W"] * 0.5) / 60    # 取 50% 换热效率
R["5_温控"] = {"被控热容_J_K": round(C), "最大漂移速率_K_min": max(T["目标漂移速率_K_min"]),
             "升温所需功率_W": round(P_rate, 1), "散热损失_10K_W": round(P_loss, 1), "合计_W": round(P_need, 1),
             "恒温槽加热_W": T["循环恒温槽85"]["加热功率_W"], "恒温槽制冷_W": T["循环恒温槽85"]["制冷功率_W"],
             "功率裕量倍数_制冷": round(T["循环恒温槽85"]["制冷功率_W"] / P_need, 1),
             "5K阶跃估算时间_min": round(step_t_min, 1), "自然冷却时间常数_min": round(tau / 60),
             "说明": "锁闭阀块的热容未计入（与缸体经端面传热，较慢）；阀块内锁闭油液温度以油温传感器实测为准"}

# ------------------------------------------------------------------ 6 泄漏模拟针阀
V = B["卡盘模拟单元"]["泄漏模拟针阀15"]
p_c = B1["卡盘液压缸12"]["夹紧压力_额定"]
q_nom = V["额定模拟值_L_min_at_3MPa"] * p_c / 3.0
R["6_泄漏模拟"] = {"调节范围_L_min_at_3MPa": V["调节范围_L_min_at_3MPa"], "额定模拟值_L_min_at_3MPa": V["额定模拟值_L_min_at_3MPa"],
                 "额定夹紧压力_MPa": p_c, "额定压力下泄漏_L_min(层流折算)": round(q_nom, 2),
                 "额定压力下泄漏功率_W": round(p_c * q_nom / 60 * 1000, 1)}

# ------------------------------------------------------------------ 汇总（供说明书与校验读取）
R["汇总"] = {
    "滑块理论分辨率_um": R["1_分辨率与行程"]["滑块理论分辨率_um"],
    "滑块轴向行程_mm": R["1_分辨率与行程"]["滑块轴向行程_mm"],
    "行程裕量倍数": R["1_分辨率与行程"]["行程裕量倍数"],
    "滚针驱动转矩_Nm": out["滚针接触"]["丝杠驱动转矩_Nm"],
    "滚针反推力_N": out["滚针接触"]["楔块反推净横向力_N"],
    "滑动驱动转矩_Nm": out["滑动接触"]["丝杠驱动转矩_Nm"],
    "床身刚度_N_um": R["4_回路刚度"]["床身拉压刚度_N_um"],
    "加载链刚度_N_um": R["4_回路刚度"]["加载链串联刚度_N_um(不含楔面接触)"],
    "刚度比": R["4_回路刚度"]["加载链/被测刚度"],
    "夹套所需功率_W": R["5_温控"]["合计_W"],
    "被控热容_J_K": R["5_温控"]["被控热容_J_K"],
    "阶跃时间_min": R["5_温控"]["5K阶跃估算时间_min"],
    "推力误差_N": R["3_推力量程"]["推力传感器误差_N"],
    "泄漏功率_W": R["6_泄漏模拟"]["额定压力下泄漏功率_W"],
}
json.dump(R, open(os.path.join(HERE, "校核计算.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)

# ------------------------------------------------------------------ 计算书
s = R["汇总"]
md = f"""# P4 试验台校核计算书

> 由 `p4_calc.py` 生成，数值见 `校核计算.json`。设计基准：`00_设计基准/P4_设计基准.json`；共用液压参数：P1 设计基准。全部为计算值，未经试验验证。

## 1 微位移加载单元的分辨率与行程
- 楔块斜率 tanθ={t}，滑块位移为楔块横向位移的 {t} 倍（缩小比 {1/t:.0f}:1）。
- 丝杠导程 {lead} mm，伺服编码器每转 {enc} 脉冲，滑块理论分辨率 = {lead}/{enc}×{t}×1000 = {res_theory_um:.4f} µm。实际分辨率受丝杠预紧、楔面接触变形和摩擦粘滑限制，设计目标 {U['位移分辨率目标_um']} µm，以位移传感器实测为准。
- 丝杠有效行程 {U['滚珠丝杠']['有效行程_mm']} mm，对应滑块轴向行程 {stroke_slider:.2f} mm；P1 设计基准中最大工件热伸长 {R['1_分辨率与行程']['需求_热伸长最大_um']} µm，行程裕量 {s['行程裕量倍数']} 倍。

## 2 驱动转矩、自锁与反驱（最大轴向加载力 {F} N）
| 接触方式 | μ | 推进横向力 /N | 丝杠转矩 /(N·m) | 反推净横向力 /N | 楔面自锁 | 额定转矩裕量 |
|---|---|---|---|---|---|---|
""" + "\n".join(f"| {k} | {v['μ']} | {v['推进楔块所需横向力_N']} | {v['丝杠驱动转矩_Nm']} | {v['楔块反推净横向力_N']} | {'是' if v['楔面自锁'] else '否'} | {v['额定转矩裕量倍数']} |"
                for k, v in out.items() if isinstance(v, dict)) + f"""

结论：{R['2_驱动与自锁']['结论']}。实施例采用滚针接触并选带抱闸伺服电机。

## 3 推力量程
目标推力 {TF['F0_可调范围'][0]}～{TF['F0_可调范围'][1]} N，允许最大油缸力 {TF['允许最大油缸力']} N；推力传感器量程 {R['3_推力量程']['推力传感器量程_N']} N、误差 {s['推力误差_N']:.0f} N，约为额定推力 ±5% 带宽的 {R['3_推力量程']['误差占额定推力带宽比例']:.0%}。

## 4 加载链刚度
床身受力截面 {A_bed} mm²、受力段长 {L_bed} mm，拉压刚度 {s['床身刚度_N_um']} N/µm；与推力传感器（{k_sens} N/µm，假设）串联为 {s['加载链刚度_N_um']} N/µm，是被测尾座双腔锁闭刚度 {k_tail} N/µm 的 {s['刚度比']} 倍。楔面接触和螺栓结合面的柔度未计入，由位移传感器直接测滑块位移消除其影响。

## 5 温控夹套
被控热容（缸筒与端盖、油液、夹套）约 {s['被控热容_J_K']} J/K；按 {max(T['目标漂移速率_K_min'])} K/min 升温需 {R['5_温控']['升温所需功率_W']} W，加 10 K 温差散热 {R['5_温控']['散热损失_10K_W']} W，合计约 {s['夹套所需功率_W']} W；恒温槽加热 {T['循环恒温槽85']['加热功率_W']} W、制冷 {T['循环恒温槽85']['制冷功率_W']} W，裕量充足。按 50% 换热效率，5 K 阶跃约 {s['阶跃时间_min']} min。

## 6 回转接头泄漏模拟
针阀调节范围 0～{V['调节范围_L_min_at_3MPa'][1]} L/min（3 MPa），额定模拟值 {V['额定模拟值_L_min_at_3MPa']} L/min；按层流折算到额定夹紧压力 {p_c} MPa 时约 {R['6_泄漏模拟']['额定压力下泄漏_L_min(层流折算)']} L/min，相当于 {s['泄漏功率_W']} W 液压功率持续损失。

## 7 防护
防护罩采用铝型材框架和 6 mm 聚碳酸酯板，防护前门滑动开启，门联锁开关与急停串入安全回路（门开时切断伺服使能和电磁阀电源）。按 GB/T 15706 的风险评估原则，液压管路最高压力 7 MPa，软管爆裂时的喷射由聚碳酸酯板阻挡（强度未作专门计算，属定性判断）。
"""
open(os.path.join(HERE, "校核计算书.md"), "w", encoding="utf-8").write(md)
print(json.dumps(R["汇总"], ensure_ascii=False, indent=1))
